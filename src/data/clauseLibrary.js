// State label (as used by detection) → which clause `state` values apply.
export function clausesForState(stateLabel, docCategory) {
  return CLAUSE_LIBRARY.filter((c) => {
    const stateOk = !stateLabel || c.state === stateLabel || c.state === "central/common";
    const typeOk = !docCategory || c.document_type === docCategory;
    return stateOk && typeOk;
  });
}
